#!/usr/bin/env python3
"""Generate video clips for each beat of a ZorkBurr recap.

Supports two video providers:
  - runway (default): Runway Gen-4 Turbo. Requires RUNWAY_KEY in .env.
    Duration: 5 or 10 seconds. No built-in audio.
  - veo: Google Veo 3.1 Lite. Requires GOOGLE_AI_STUDIO in .env.
    Duration: 4, 6, or 8 seconds. Built-in ambient audio.

Usage:
    uv run scripts/generate_recap_video.py --episode-id ep98 --all-beats --scene-stills
    uv run scripts/generate_recap_video.py --episode-id ep98 --all-beats --provider veo
    uv run scripts/generate_recap_video.py --episode-id ep98 --beat-index 3
    uv run scripts/generate_recap_video.py --episode-id ep98 --all-beats --dry-run
"""
