# scripts/generate_character_reference.py (STYLE_PROMPTS["cinematic"]).
BASE_CHARACTER = (
    "A lone adventurer in a worn brown travelling cloak with the hood "
    "raised, face half-concealed in shadow. Medium build, dark wool tunic, "
    "heavy trousers, mud-caked leather boots."
)

# --- Provider: Veo ---
VEO_MODEL_ID = "veo-3.1-lite-generate-preview"
VEO_VALID_DURATIONS = (4, 6, 8)
VEO_PRICE_PER_SECOND = {"720p": 0.05, "1080p": 0.08}

# --- Provider: Runway ---
