def snap_duration(requested: int, provider: str) -> int:
    """Snap a requested duration up to the nearest valid value for the provider."""
    valid = VEO_VALID_DURATIONS if provider == "veo" else RUNWAY_VALID_DURATIONS
    clamped = max(min(requested, valid[-1]), valid[0])
    for v in valid:
        if clamped <= v:
            return v
    return valid[-1]

